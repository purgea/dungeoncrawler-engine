        poly('#596164', [[22, 11], [26, 7], [37, 7], [41, 14], [40, 28], [24, 29], [21, 22]]);
        poly('#89908a', [[24, 11], [29, 9], [30, 19], [23, 18]]);
        rect('#27343b', 22, 19, 20, 5);
        rect('#ff793e', 24, 20, 6, 2);
        rect('#ffb864', 33, 20, 6, 2);
        rect('#b5a079', 31, 12, 2, 17);
