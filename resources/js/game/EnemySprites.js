        poly('#54435d', [[31, 10], [25, 22], [23, 33], [20, 28], [23, 16]]);
        poly('#0d1119', [[30, 18], [37, 20], [40, 33], [23, 33], [25, 23]]);
        poly('#aeb7a1', [[26, 23], [35, 22], [38, 27], [36, 34], [29, 38], [25, 32]]);
        rect('#182325', 26, 27, 4, 3);
        rect('#182325', 33, 26, 4, 3);
        rect('#70ffd0', 27, 27, 3, 1);
        rect('#70ffd0', 34, 26, 3, 1);
        rect('#2c3536', 31, 31, 2, 3);
        [28, 31, 34].forEach((x) => rect('#e0d9ba', x, 35, 1, 3));
        poly('#352d44', [[20, 35], [28, 41], [37, 39], [44, 36], [41, 57], [47, 86], [36, 84], [32, 90], [26, 85], [16, 87], [23, 57]]);
        poly('#554362', [[24, 39], [29, 43], [25, 84], [19, 86], [23, 61]]);
        poly('#211f31', [[35, 42], [40, 39], [39, 61], [44, 83], [34, 83]]);
        rect('#a38754', 24, 49, 16, 3);
        rect('#665136', 25, 53, 14, 2);
        rect('#bcaa7a', 30, 44, 4, 7);
        rect('#81edc8', 31, 46, 2, 3);
        poly('#45364f', [[15, 38], [23, 38], [18, 49], [13, 60 + step], [6, 57 + step]]);
        poly('#49394d', [[42, 38], [49, 40], [55, 54 - step], [49, 60 - step], [44, 49]]);
        rect('#c6c3a2', 7, 54 + step, 7, 4);
        rect('#c6c3a2', 49, 53 - step, 6, 5);
        // A crooked staff with a captive green flame.
        rect('#38281e', 53, 27, 3, 61);
        rect('#9f8150', 53, 28, 1, 57);
        poly('#9e8b5d', [[49, 24], [51, 20], [51, 27], [57, 27], [59, 20], [61, 25], [57, 31], [52, 30]]);
